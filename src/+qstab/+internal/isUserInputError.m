function tf = isUserInputError(ME)
%ISUSERINPUTERROR True only for a known user diagnostic from qstab code.
% A public boundary hides only recognised argument errors originating in
% this package. Unexpected faults, numerical errors and original causes
% keep their complete diagnostic stack. Never classify by message text.
try
    tf = classify(ME);
catch
    tf = false;
end
end

function tf = classify(ME)
tf = false;
if isa(ME,'MException')
    if ~isempty(ME.cause) || (isprop(ME,'Correction') && ~isempty(ME.Correction)), return; end
elseif ~isstruct(ME) || ~isscalar(ME) || ~isfield(ME,'identifier') || ...
        ~isfield(ME,'stack') || (isfield(ME,'cause') && ~isempty(ME.cause)) || ...
        (isfield(ME,'Correction') && ~isempty(ME.Correction))
    return
end
if isempty(ME.stack) || ~ischar(ME.identifier), return; end

persistent userIDs parserIDs
if isempty(userIDs)
    groups = { ...
        'qstab:family:', {'Arguments','BoundedMargin','Bounds','Coefficients','Definition', ...
         'ExtendParameter','Generators','Grade','IntervalOrder','Kind','MarginKind','MissingField', ...
         'Option','OptionConflict','Options','SamplingPeriod','Side','Variable','Vertices'}; ...
        'qstab:randfamily:', {'Argument','Bounds','Count','Degree','Duplicate','Kind','MissingValue', ...
         'Option','Positional','SamplingPeriod','Seed','Side','Variable','Width','Domain','Format'}; ...
        'qstab:sample:', {'Family','Count','Options','Sampling','Seed','SampleBounds','Frequency', ...
         'Axis','Projection','Directions','Grade','Variable'}; ...
        'qstab:', {'CoefficientSizeMismatch','ComponentSizeMismatch','EmptyPolynomial','GradeTooSmall', ...
         'InconsistentDomain','InvalidComponents','InvalidDomain','InvalidGrade','InvalidMatrixVariable', ...
         'InvalidMethod','InvalidOptions','InvalidPolynomial','InvalidTolerance','InvalidType', ...
         'InvalidVariable','LeadingCoefficientMissing','NonfiniteInput','NotMatrix', ...
         'NotScalarPolynomial','NotSquareMatrix','NotSquarePolynomial','UnknownOption', ...
         'UnsupportedInput','ZeroPolynomial'}; ...
        'qstab:familycomponents:', {'BoundsOrder','IntervalOrder','IntervalSize','InvalidBounds', ...
         'InvalidGenerators','InvalidInterval','InvalidPolynomial','InvalidSide','InvalidStruct', ...
         'InvalidVertices','MissingField','UncertaintyRequired','UnknownUncertainty'}; ...
        'qstab:ball:', {'Exponent','Weights'}; 'qstab:ballradius:', {'DegreeLimit','Variable'}; ...
        'qstab:ballset:', {'Radius'}; 'qstab:ballstable:', {'Radius'}; ...
        'qstab:ballvalue:', {'Arguments'}; 'qstab:box:', {'Weights'}; ...
        'qstab:boxradius:', {'Boundary','DegreeLimit','Method','Variable'}; ...
        'qstab:boxstable:', {'DegreeLimit','Method','Radius','Variable'}; ...
        'qstab:boxvalue:', {'Evaluation','Point'}; ...
        'qstab:certificateData:', {'Report'}; ...
        'qstab:certificateEnclosure:', {'Family','Frequency','Index','NoGeometry'}; ...
        'qstab:diagnostics:', {'Parent','Sides','Visible'}; ...
        'qstab:discretepair:', {'Grade','Variable'}; 'qstab:eigpairs:', {'NotSquare','Output'}; ...
        'qstab:freqmargin:', {'Angle','CheckNominal','Degree','Frequency','Grade','Options', ...
         'Side','Tolerance','Variable'}; ...
        'qstab:kharitonovcube:', {'Variable'}; 'qstab:leadingbound:', {'Variable'}; ...
        'qstab:lyapoperator:', {'Shape'}; 'qstab:plotCertificate:', {'Indices','Units','View'}; ...
        'qstab:plotEnclosure:', {'Indices','Input','Lambda','Samples'}; ...
        'qstab:plotSpectrum:', {'Components','Dimension','Input','NaN','NameValue', ...
         'NotEnoughInputs','Option','OptionName','Parent','Tolerance','Variable','Visible'}; ...
        'qstab:plotValueSet:', {'Connect','Input','LambdaIndex','NameValue','Option','OptionName','Parent','Visible'}; ...
        'qstab:plotWitness:', {'Representation','Witness'}; ...
        'qstab:raymargin:', {'Direction','Domain','Grade','GuardBudget','MatrixShape','Option', ...
         'Options','OrderLimit','Tolerance','VerifyBoundary'}; ...
        'qstab:robuststable:', {'InvalidVariable','Method','ReductionMethod','UnsupportedType'}; ...
        'qstab:stabilityradius:', {'Budget','DegreeLimit','Grade','Options','Side','Variable'}; ...
        'qstab:valueenclosure:', {'Bounds','Lambda','ParameterBoxes','VertexCells','Weights'}; ...
        'qstab:valueset:', {'Lambda','NameValue','NotEnoughInputs','Option','OptionName', ...
         'Simplex','Vertices','WeightSize','Weights'}; ...
        'qstab:witnessData:', {'Report','Variable','Witness'}; ...
        'qstab:zeroexclude:', {'Reduction','Variable'}};
    userIDs = {};
    for k=1:size(groups,1)
        userIDs = [userIDs strcat(groups{k,1},groups{k,2})]; %#ok<AGROW>
    end
    parserIDs = strcat('MATLAB:InputParser:', ...
        {'UnmatchedParameter','AmbiguousParameter','ArgumentFailedValidation', ...
         'ParamMissingValue','ParamMustBeChar','ParamNameMustBeChar'});
end
isParser = any(strcmp(ME.identifier,parserIDs));
% Only explicit argument-count guards (e.g. the eigpairs input check).
isCount = any(strcmp(ME.identifier,{'MATLAB:narginchk:notEnoughInputs', ...
    'MATLAB:narginchk:tooManyInputs','MATLAB:nargoutchk:tooManyOutputs'}));
if ~isParser && ~isCount && ~any(strcmp(ME.identifier,userIDs)), return; end
for k = 1:numel(ME.stack)
    frame = ME.stack(k);
    if isParser && isParserFrame(frame), continue; end
    % Check the FIRST non-parser frame, never just any qstab frame further
    % down the stack (foreign code may have been called by a wrapper).
    tf = isProjectFrame(frame.file);
    return
end
end

function tf = isParserFrame(frame)
% If inputParser presents its own frames (rather than citing parse's caller),
% skip only the MATLAB installation's own inputParser implementation.
f = canonical(frame.file); mr = canonical(matlabroot);
[~,stem] = fileparts(f);
tf = strncmp(f,[mr '/'],numel(mr)+1) && ...
     (strcmpi(stem,'inputparser') || ~isempty(strfind(lower(f),'/@inputparser/'))); %#ok<STREMP>
end

function tf = isProjectFrame(file)
tf = false;
if isempty(file), return; end
[folder,~,ext] = fileparts(file);
if ~strcmpi(ext,'.m') && ~strcmpi(ext,'.p'), return; end
% Use the actual classifier location, never a similarly named foreign path.
core = canonical(fileparts(fileparts(mfilename('fullpath'))));
tf = any(strcmp(canonical(folder),{core,[core '/+internal']}));
end

function p = canonical(p)
p = strrep(p,'\','/');
if ispc, p=lower(p); end
end
