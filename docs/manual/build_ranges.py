"""Refresh the line ranges of the single-source MATLAB listings; no third-party dependencies."""
import re
from pathlib import Path
folder=Path(__file__).resolve().parent
source=folder.parent.parent / 'examples' / 'qstab_guide_example.m'
lines=source.read_text(encoding='utf8').splitlines()
ranges={}
for n,line in enumerate(lines,1):
    m=re.fullmatch(r'%<(/?)(G\d{2})>',line)
    if m:
        ranges.setdefault(m[2],{})[m[1]]=n + (1 if not m[1] else -1)
out='% Generated by build_ranges.py from examples/qstab_guide_example.m\n'
for key,v in sorted(ranges.items()):
    out+=r'\expandafter\def\csname Lab'+key+r'\endcsname{\lstinputlisting[firstline='+str(v[''])+',lastline='+str(v['/'])+']{../../examples/qstab_guide_example.m}}'+'\n'
assert len(ranges)==11
(folder/'guide_ranges.tex').write_text(out,encoding='utf8')
