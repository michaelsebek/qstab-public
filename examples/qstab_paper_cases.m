    'exhaustiveFiniteVerticesNotFullFamily', ...
    struct('minimum',[999/500,3991003/500000,2497001/250000, ...
    1987005997/500000000,1932102962993003/250000000000000]), ...
    struct('L',L,'U',U,'interior',[2 1 1;1 .5 0;-2 -1 0;1 1 0]));
