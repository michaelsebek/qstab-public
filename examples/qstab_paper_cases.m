function b=conjQ(a),b=a;b(2:4)=-b(2:4);end
function c=mulQ(a,b)
c=[a(1)*b(1)-dot(a(2:4),b(2:4));a(1)*b(2:4)+b(1)*a(2:4)+cross(a(2:4),b(2:4))];
end
